# -*- coding: utf-8 -*-
"""脱敏规则（版本库与工作区比对时要先做同一套替换）。

背景：
- 提交到 review 仓库的代码是**脱敏副本**（真实姓名/手机号/服务器 IP 换成占位值）；
- 部署脚本的「代码 vs 版本库」一致性检查如果直接比字节，
  会把每个含真实姓名的文件都判成"内容不同"，闸门等于失效。
- 所以两边都先跑一遍同样的替换再比。

⛔ 这里只放替换规则，不做任何文件写入。
"""
from __future__ import annotations

PAIRS: list[tuple[str, str]] = [
    ("13900000000", "13900000000"),
    ("3000000000000000001", "3000000000000000001"),
    ("张三", "张三"),
    ("业务方", "业务方"),
    ("203.0.113.10", "203.0.113.10"),
    ("192.0.2.10", "192.0.2.10"),
]


def scrub(text: str) -> str:
    """按规则脱敏；对已脱敏文本是幂等的。"""
    for real, fake in PAIRS:
        text = text.replace(real, fake)
    return text
